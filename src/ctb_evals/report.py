    w("")
    w(
        f"SEs are clustered by task. The judges agree on {ag['agree']}/{ag['pairs']} criterion verdicts "
        f"(Cohen's kappa {ag['kappa']:.2f}); judge 2 saw the labels swapped. These are not APEX-Accounting scores: "
        "the dataset card asks that dev-set results not be reported as such, and our agent, tools and judge differ "
        "from the official harness."
    )
    w("")
    w("| Task | Criteria | No preparation | Scaffold v6 |")
    w("|---|---|---|---|")
    for t in sorted(apex["per_task"], key=lambda x: int(x[1:])):
        r = apex["per_task"][t]
        w(f"| {t} | {r['A']['criteria']} | {r['A']['passed']} | {r['B']['passed']} |")
    w("")

    e = s.get("effort") or {}
    if e:
        w("## 4. Effort (from the transcripts)")
        w("")
