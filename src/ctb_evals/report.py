            f"| {ARM_LABEL.get(arm, arm)} | {len(a['teams'])} | {pct(a['accuracy'], a['se'])} | "
            f"{100 * a['sd_across_teams']:.1f} | {pct(b['accuracy'], b['se'])} | {100 * b['sd_across_teams']:.1f} |"
