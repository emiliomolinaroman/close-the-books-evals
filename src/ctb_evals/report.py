"""Render ``results/summary.json`` as ``results/RESULTS.md``, and the headline block of the README.

Every number in the README and the write-up comes from here; ``tests/test_report.py`` checks
that the README block matches the committed summary.
"""

from __future__ import annotations

from typing import Any

ARM_LABEL = {"no-prep": "No preparation", "scaffold-v6": "Scaffold v6", "scaffold-v7": "Scaffold v7"}
README_START = "<!-- results:start (generated by `ctb report --readme`; do not edit) -->"
README_END = "<!-- results:end -->"


def pct(x: float, se: float | None = None) -> str:
    return f"{100 * x:.1f}%" + (f" ({100 * se:.1f})" if se is not None else "")


def pts(x: float, se: float | None = None) -> str:
    return f"{100 * x:+.1f}" + (f" ({100 * se:.1f})" if se is not None else "")


def ci(lo: float, hi: float) -> str:
    return f"[{100 * lo:+.1f}, {100 * hi:+.1f}]"


CITATION_LABEL = {
    "exact": "Same documents as the key",
    "over": "The key's documents plus others",
    "under": "Some of the key's documents, nothing else",
    "partial": "Some in common, neither contains the other",
    "disjoint": "No document in common",
    "missing": "No `doc_refs`",
}


def team_mean(c: dict[str, Any], k: str) -> float:
    """Mean of one citation figure over the code-writing teams."""
    teams = c["code_teams"]
    return sum(float(v[k]) for v in teams.values()) / len(teams)


def headline(s: dict[str, Any]) -> str:
    """The short results table embedded in the README."""
    f = s["finbalance"]["direct"]["full"]
    p, bs, f1 = f["paired"], f["bs_exact_paired"], f["entry_f1_strict_ci95"]
    ds, cs = f["direct"], f["code_summary_mean"]
    ap = s["apex"]["judge1"]
    rows = [
        f"| FinBalance, hidden split A ({f['n']} packets) | Answering directly | "
        f"Writing code ({len(s['finbalance']['direct']['code_teams'])} teams) | Gap, 95% CI |",
        "|---|---|---|---|",
        f"| Packet fully right | {pct(f['direct_accuracy'], f['direct_se'])} | {pct(f['code_accuracy'], f['code_se'])} | "
        f"{pts(p['diff'])} {ci(p['ci95_low'], p['ci95_high'])} |",
        f"| Balance sheet exact (clean packets) | {pct(ds['bs_exact'])} | {pct(cs['bs_exact'])} | "
        f"{pts(bs['diff'])} {ci(bs['ci95_low'], bs['ci95_high'])} |",
        f"| Entries right *and* citing the right documents (F1) | {ds['entry_f1_strict']:.2f} | "
        f"{cs['entry_f1_strict']:.2f} | {f1['diff']:+.2f} [{f1['ci95_low']:+.2f}, {f1['ci95_high']:+.2f}] |",
        *_tolerant_row(f),
        f"| Contradiction code exact ({ds['n_inconsistent']} packets) | {pct(ds['inconsistency_code_accuracy'])} | "
        f"{pct(cs['inconsistency_code_accuracy'])} | |",
        "",
        f"APEX-Accounting dev set, 89 rubric criteria, blind judge: no preparation {pct(ap['A']['rate'], ap['A']['se_clustered'])}, "
        f"scaffold {pct(ap['B']['rate'], ap['B']['se_clustered'])} (difference {pts(ap['diff'], ap['diff_se_clustered'])}). "
        "Standard errors in parentheses.",
        *_team_ci_note(f),
        *_followup_note(s["finbalance"]["direct"]),
        *_teaching_note(s["finbalance"]["direct"]),
    ]
    return "\n".join(rows)


def _followup_note(d: dict[str, Any]) -> list[str]:
    e = d.get("examples_followup")
    if not e:
        return []
    ctl, ex, g = e["arms"][e["control"]], e["arms"][e["examples"]], e["gap_closed"]
    return [
        "",
        f"Follow-up, {e['n']} of those packets, pre-registered: given three solved examples, the direct answer's entry "
        f"F1 with citations rises from {ctl['entry_f1_strict']:.2f} to {ex['entry_f1_strict']:.2f} (code teams "
        f"{e['code_teams']['entry_f1_strict']:.2f}), closing {g['value']:.2f} [{g['ci95'][0]:.2f}, {g['ci95'][1]:.2f}] "
        "of the citation gap.",
    ]


def _teaching_note(d: dict[str, Any]) -> list[str]:
    t = d.get("teaching_followup")
    if not t:
        return []
    parts = []
    for label in ("P", "E", "S", "Ma", "Mb"):
        if label in t["arms"]:
            g = t["arms"][label]["gap_closed"]
            parts.append(f"{TEACHING_LABEL[label]} {g['value']:.2f} [{g['ci95'][0]:.2f}, {g['ci95'][1]:.2f}]")
    return [
        "",
        f"Second follow-up, same {t['n']} packets, pre-registered, share of the citation gap closed against its own "
        "control: " + "; ".join(parts) + ".",
    ]


def _team_ci_note(f: dict[str, Any]) -> list[str]:
    c = f.get("ci95_with_team_variance")
    if not c:
        return []
    return [
        "",
        f"The CIs above hold the eight programs fixed. Counting run-to-run variance between teams, the fully-right "
        f"gap is {pts(f['paired']['diff'])} {ci(*c)}: suggestive, not established.",
    ]


def _sensitivity(f: dict[str, Any]) -> list[str]:
    sens = f.get("sensitivity")
    if not sens:
        return []
    label = {
        "without_scaffold_v7": "Without the two v7 teams (their scaffold was revised after reading hidden-A errors)",
        "no_prep_only": "No-preparation teams only",
    }
    out = [
        "",
        "Sensitivity, chosen after seeing the results (fully right, code minus direct, counting team variance):",
        "",
        "| Code teams | Teams | Code | Gap | 95% CI |",
        "|---|---|---|---|---|",
        f"| All eight (as reported) | {len(f.get('code_teams', [])) or 8} | {pct(f['code_accuracy'])} | {pts(f['paired']['diff'])} | "
        f"{ci(*f['ci95_with_team_variance'])} |",
    ]
    for k, v in sens.items():
        out.append(
            f"| {label.get(k, k)} | {len(v['teams'])} | {pct(v['code_accuracy'])} | {pts(v['diff'])} | "
            f"{ci(*v['ci95_with_team_variance'])} |"
        )
    return out


def _cost(s: dict[str, Any]) -> list[str]:
    e, pr = s.get("effort") or {}, s["study"].get("list_prices_usd_per_mtok")
    if not pr or "direct_answer" not in e or "finbalance_team" not in e:
        return []

    def usd(x: dict[str, Any], write: float) -> float:
        return (
            float(
                x["input_tokens_per_run"] * pr["input"]
                + x["cache_creation_input_tokens_per_run"] * write
                + x["cache_read_input_tokens_per_run"] * pr["cache_read"]
                + x["output_tokens_per_run"] * pr["output"]
            )
            / 1e6
        )

    da, ft = e["direct_answer"], e["finbalance_team"]
    share = da["runs"] / da["packets_answered"]
    team = [usd(ft, pr["cache_write_5m"]), usd(ft, pr["cache_write_1h"])]
    pkt = [usd(da, pr["cache_write_5m"]) * share, usd(da, pr["cache_write_1h"]) * share]
    even = sorted(t / p for t, p in zip(team, pkt, strict=True))
    more = "more than" if all(ft["runs"] * x > 143 * y for x, y in zip(team, pkt, strict=True)) else "about the same as"
    return [
        "",
        f"At {pr['model']} list prices (input, cache writes, cache reads and output; 5-minute or 1-hour cache "
        f"writes), one code-writing team cost ${team[0]:.2f} to ${team[1]:.2f} and answering directly "
        f"${pkt[0]:.2f} to ${pkt[1]:.2f} per packet, so one program pays for itself after about "
        f"{even[0]:.0f} to {even[1]:.0f} packets. The study ran {ft['runs']} teams (${ft['runs'] * team[0]:.0f} to "
        f"${ft['runs'] * team[1]:.0f}), {more} answering the 143 hidden-A packets once (${143 * pkt[0]:.0f} to "
        f"${143 * pkt[1]:.0f}); the practice rounds that shaped the scaffold are not counted.",
    ]


def _tolerant_row(f: dict[str, Any]) -> list[str]:
    c = f.get("citations")
    if not c:
        return []
    t = c["entry_f1_tolerant_ci95"]
    return [
        f"| Entries right, citing *at least* the right documents (F1) | {c['direct']['entry_f1_tolerant']:.2f} | "
        f"{team_mean(c, 'entry_f1_tolerant'):.2f} | {t['diff']:+.2f} [{t['ci95_low']:+.2f}, {t['ci95_high']:+.2f}] |"
    ]


def _citations(f: dict[str, Any]) -> list[str]:
    c = f.get("citations")
    if not c:
        return []
    d, t = c["direct"], c["entry_f1_tolerant_ci95"]
    out = [
        "",
        "**Where the citation gap comes from.** Entries with the right accounts and amount on clean packets, "
        "by how their `doc_refs` differ from the key (`ctb_evals/finbalance/citations.py`; not part of the "
        "original scorer):",
        "",
        "| Citation | Answering directly (entries) | Writing code (entries, mean per team) |",
        "|---|---|---|",
    ]
    out += [f"| {lab} | {d[k]} | {team_mean(c, k):.1f} |" for k, lab in CITATION_LABEL.items()]
    out += [
        f"| Entry F1 citing *at least* the key's documents | {d['entry_f1_tolerant']:.3f} | "
        f"{team_mean(c, 'entry_f1_tolerant'):.3f} |",
        "",
    ]
    extra, lacking = d["extra_types"], d["lacking_types"]

    def top(c: dict[str, int], n: int) -> str:  # summary.json is written with sorted keys
        return ", ".join(f"`{k}` {v}" for k, v in sorted(c.items(), key=lambda kv: (-kv[1], kv[0]))[:n])

    top_extra, top_lacking = top(extra, 3), top(lacking, 5)
    out.append(
        f"Counting an entry as right when it cites at least the key's documents, the gap is {t['diff']:+.3f} "
        f"(packet-bootstrap 95% CI [{t['ci95_low']:+.3f}, {t['ci95_high']:+.3f}]). Extra documents cited by the "
        f"direct answer ({sum(extra.values())}): {top_extra}. Key documents it left out ({sum(lacking.values())}): "
        f"{top_lacking}."
    )
    return out


