def teaching_reading(label: str, g: dict[str, Any]) -> str:
    """The reading rule of experiments/2026-11/followup_teaching/PREREGISTRATION.md, applied as written."""
    v, (lo, hi) = g["value"], g["ci95"]
    if label == "P":
        if v >= 0.25 and lo > 0:
            return "part of the gap is being told that citations count"
        if v < 0.10 or lo <= 0 <= hi:
            return "being told the scoring does not explain the gap"
        return "in between the two pre-registered readings"
    if label == "E":
        return "replication of 1b"
    if v >= 0.5 and lo > 0:
        return "closes most of the gap"
    if v < 0.25:
        return "does not close the gap"
    return "partly"


def _teaching(d: dict[str, Any]) -> list[str]:
    t = d.get("teaching_followup")
    if not t:
        return []
    ctl, code, ses = t["control_metrics"], t["code_teams"], t["sessions"]

    def row(label: str, a: dict[str, Any], extra: str) -> str:
        c = a["citations"]
        cost = ses.get(label, {}).get("cost_usd_list_price")
        return (
            f"| {TEACHING_LABEL[label]} | {pct(a['accuracy'])} | {a['entry_f1_strict']:.3f} | {a['entry_f1_tolerant']:.3f} | "
            f"{c['over']} | {a['entries_missing_a_key_document']} | {pct(a['inconsistency_recall'])} | {extra} | "
            f"{'' if cost is None else f'{cost:.2f}'} |"
        )

    out = [
        "",
        f"## 1c. Follow-up (8 November): what teaches the convention? ({t['n']} packets)",
        "",
        "Same packets and groups as 1b, one fresh headless Claude Code session (`claude -p`, Claude Opus 5.5) per "
        "group and arm, driven by a harness in code that fixes the model, the tools and the turn limit on the "
        "command line. Five ways to teach the citation convention, each against the same control: being told "
        "how answers are scored (the section only the code teams' brief had), the three solved examples of 1b, "
        "Anthropic's `journal-entry-prep` skill installed as shipped, and notes the agent wrote itself over 8 "
        "checked practice packets (two independent chains). Pre-registered in "
        "`experiments/2026-11/followup_teaching/PREREGISTRATION.md`.",
        "",
        f"| Arm | Fully right ({t['n']}) | Entry F1 with doc refs ({t['n_clean']} clean) | Entry F1, at least the key's "
        "documents | Entries only adding documents | Entries missing one of the key's documents | Contradictions "
        "caught | Share of the gap closed [95% CI] | List-price USD per packet |",
        "|---|---|---|---|---|---|---|---|---|",
        row("C", ctl, ""),
    ]
    for label, a in t["arms"].items():
        g = a["gap_closed"]
        out.append(row(label, a["metrics"], f"{g['value']:.2f} [{g['ci95'][0]:.2f}, {g['ci95'][1]:.2f}]"))
    out += [
        f"| Writing code (mean of {len(code['teams'])} teams) | {pct(code['accuracy'])} | {code['entry_f1_strict']:.3f} | "
        f"{code['entry_f1_tolerant']:.3f} | | | | | |",
        "",
        "**Primary (pre-registered), entry F1 with doc refs, arm minus control, and the reading the rule gives:**",
        "",
    ]
    for label, a in t["arms"].items():
        p, g = a["entry_f1_strict_diff"], a["gap_closed"]
        out.append(
            f"* {TEACHING_LABEL[label]}: {p['diff']:+.3f} [{p['ci95'][0]:+.3f}, {p['ci95'][1]:+.3f}]; gap closed "
            f"{g['value']:.2f} [{g['ci95'][0]:.2f}, {g['ci95'][1]:.2f}]: {teaching_reading(label, g)}."
        )
    s = ses.get("S", {})
    tr = t["training"]
    steps = {c: sum(1 for x in tr[c] if x["correct"]) for c in tr}
    out += [
        "",
        f"Five comparisons against one control, no multiplicity correction ({t['bootstrap']['reps']:,} paired "
        f"resamples of the {t['n_clean']} clean packets). The skill was called in {s.get('sessions_that_called_the_skill', 0)} "
        f"of {s.get('sessions', 0)} sessions. The memory chains got {steps['a']} and {steps['b']} of their 8 practice "
        f"packets fully right and ended with notes of {t['notes_words']['a']} and {t['notes_words']['b']} words "
        "(`experiments/2026-11/followup_teaching/logs/`). Fully right is underpowered here; no conclusion rests on it. "
        "The 1b runs used subagents on Claude Code 2.1.316; these use `claude -p` on 2.1.319, so compare arms only "
        "within this table.",
    ]
    return out


def _followup_reading(d: dict[str, Any]) -> str:
    e = d.get("examples_followup")
    if not e:
        return " This study cannot separate writing code from seeing solved examples."
    p, g = e["entry_f1_strict_diff"], e["gap_closed"]
    ctl, ex = e["arms"][e["control"]], e["arms"][e["examples"]]
    miss = e["code_teams"]["entries_missing_a_key_document"].values()
    return (
        f" A pre-registered follow-up (section 1b) gave the direct answer three solved examples: on {e['n']} packets "
        f"its entry F1 with doc refs rose by {p['diff']:+.2f} [{p['ci95'][0]:+.2f}, {p['ci95'][1]:+.2f}], closing "
        f"{g['value']:.2f} [{g['ci95'][0]:.2f}, {g['ci95'][1]:.2f}] of the gap to the code teams. Entries that only "
        f"add documents fell from {ctl['citations']['over']} to {ex['citations']['over']}; entries missing one of the "
        f"key's documents fell less, from {ctl['entries_missing_a_key_document']} to "
        f"{ex['entries_missing_a_key_document']} (code teams {min(miss)} to {max(miss)}). The pre-registered rule "
        'calls a share of 0.5 or more "most of the gap"; the interval, and 0.45 measured against the study\'s own '
        'direct trials, support "about half", which is how the README reads it. What the examples fixed least is '
        "the documents the direct answer leaves out." + _teaching_reading(d)
    )


def _teaching_reading(d: dict[str, Any]) -> str:
    t = d.get("teaching_followup")
    if not t:
        return ""
    a = t["arms"]

    def g(k: str) -> str:
        x = a[k]["gap_closed"]
        return f"{x['value']:.2f} [{x['ci95'][0]:.2f}, {x['ci95'][1]:.2f}]"

    miss = {k: a[k]["metrics"]["entries_missing_a_key_document"] for k in ("Ma", "Mb")}
    return (
        f" A second pre-registered follow-up (section 1c) separated the causes on the same packets: notes the agent "
        f"wrote itself after 8 practice packets checked by the scorer closed {g('Ma')} and {g('Mb')} of the gap in two "
        f"chains, and cut entries missing one of the key's documents from {t['control_metrics']['entries_missing_a_key_document']} "
        f"to {miss['Ma']} and {miss['Mb']}; the three examples, repeated, closed {g('E')}; being told that citations "
        f"are scored closed {g('P')}, and Anthropic's journal-entry-prep skill {g('S')}. What closes the gap is "
        "checked practice, not code and not knowing the scoring."
    )


def _convention_reading(b: dict[str, Any] | None) -> str:
    if not b:
        return ""
    return (
        f" In the public FinBalance release every record ({b['records_with_bank_statement']:,} of {b['records']:,}) has "
        f"a bank statement and {b['key_entries_citing_bank_statement']:,} of {b['key_entries']:,} key entries cite one. The "
        "FinBalance authors report document-reference mismatches on 52% of expected postings for Gemini 3 Flash on "
        "their 143-record compact split; their evidence-only condition, which drops every document no key entry "
        "cites, lowers that by 26 points."
    )


